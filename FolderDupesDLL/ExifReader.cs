using System;
using System.IO;
using System.Text;

public class ExifReader : IDisposable
{
	BinaryReader br;

	public ExifReader(BinaryReader br)
	{
		this.br = br;
	}

	public void Dispose()
	{
		br?.Dispose();
	}

	private ushort ReadBigEndianUInt16()
	{
		var bytes = br.ReadBytes(2);
		if (bytes.Length < 2) return 0;
		return (ushort)((bytes[0] << 8) | bytes[1]);
	}

	private ushort ReadUInt16(byte[] data, int offset, bool littleEndian)
	{
		return littleEndian
			? (ushort)(data[offset] | (data[offset + 1] << 8))
			: (ushort)((data[offset] << 8) | data[offset + 1]);
	}

	private uint ReadUInt32(byte[] data, int offset, bool littleEndian)
	{
		return littleEndian
			? (uint)(data[offset] | (data[offset + 1] << 8) | (data[offset + 2] << 16) | (data[offset + 3] << 24))
			: (uint)((data[offset] << 24) | (data[offset + 1] << 16) | (data[offset + 2] << 8) | data[offset + 3]);
	}

	private string ReadAsciiString(byte[] data, int offset, int count)
	{
		if (offset < 0 || count <= 0 || offset + count > data.Length) return null;
		var s = Encoding.ASCII.GetString(data, offset, count).TrimEnd('\0', ' ');
		// print value as hex dump
		//Console.WriteLine($"Value: {BitConverter.ToString(Encoding.ASCII.GetBytes(s))}");
		return s;
	}

	private bool TryGetExifValue(byte[] tiffData, int ifdOffset, bool littleEndian, int tagId, out string value)
	{
		value = null;
		if (ifdOffset < 0 || ifdOffset + 2 > tiffData.Length) return false;

		int entryCount = ReadUInt16(tiffData, ifdOffset, littleEndian);
		int entriesStart = ifdOffset + 2;

		for (int i = 0; i < entryCount; i++)
		{
			int entryOffset = entriesStart + (i * 12);
			if (entryOffset + 12 > tiffData.Length) return false;

			int entryTag = ReadUInt16(tiffData, entryOffset, littleEndian);
			if (entryTag != tagId) continue;

			int type = ReadUInt16(tiffData, entryOffset + 2, littleEndian);
			uint count = ReadUInt32(tiffData, entryOffset + 4, littleEndian);
			if (type != 2) return false; // ASCII only

			int byteCount = (int)count;
			int tiffStart = 6; // TIFF header starts at offset 6 in the EXIF payload
			//Console.WriteLine($"Found tag {tagId:X4} at offset {entryOffset:X4}, type {type}, count {count}, byteCount {byteCount}");
			int actualOffset = byteCount <= 4 ? entryOffset + 8 : tiffStart + (int)ReadUInt32(tiffData, entryOffset + 8, littleEndian);
			value = ReadAsciiString(tiffData, actualOffset, byteCount);
			return value != null;
		}

		return false;
	}

	private bool TryGetExifOffsetTag(byte[] tiffData, int ifdOffset, bool littleEndian, int tagId, out int offset)
	{
		offset = 0;
		if (ifdOffset < 0 || ifdOffset + 2 > tiffData.Length) return false;

		int entryCount = ReadUInt16(tiffData, ifdOffset, littleEndian);
		int entriesStart = ifdOffset + 2;

		for (int i = 0; i < entryCount; i++)
		{
			int entryOffset = entriesStart + (i * 12);
			if (entryOffset + 12 > tiffData.Length) return false;
			if (ReadUInt16(tiffData, entryOffset, littleEndian) != tagId) continue;
			if (ReadUInt16(tiffData, entryOffset + 2, littleEndian) != 4) return false;
			offset = (int)ReadUInt32(tiffData, entryOffset + 8, littleEndian);
			return true;
		}

		return false;
	}

	private bool TryReadExifTag(byte[] exifPayload, int tagId, out string value)
	{
		value = null;
		if (exifPayload == null || exifPayload.Length < 14) return false;
		if (exifPayload[0] != (byte)'E' || exifPayload[1] != (byte)'x' || exifPayload[2] != (byte)'i' || exifPayload[3] != (byte)'f') return false;
		if (exifPayload[4] != 0 || exifPayload[5] != 0) return false;

		int tiffStart = 6;
		bool littleEndian;
		if (exifPayload[tiffStart] == (byte)'I' && exifPayload[tiffStart + 1] == (byte)'I') littleEndian = true;
		else if (exifPayload[tiffStart] == (byte)'M' && exifPayload[tiffStart + 1] == (byte)'M') littleEndian = false;
		else return false;

		if (ReadUInt16(exifPayload, tiffStart + 2, littleEndian) != 42) return false; // TIFF magic number
		uint ifd0Offset = ReadUInt32(exifPayload, tiffStart + 4, littleEndian); // Offset to IFD0, that is the first Image File Directory
		int ifd0 = tiffStart + (int)ifd0Offset;
		if (ifd0 < tiffStart || ifd0 >= exifPayload.Length) return false;

		// IFD0 contains the main image metadata, while the Exif IFD contains additional metadata. Some tags are stored in IFD0, while others are in the Exif IFD. We need to check both locations.

		// If the tag is in IFD0, read it directly
		var ifd0Tags = new int[] { 0x010F, 0x0110, 0x0131, 0x0132 }; // Manufacturer, Model, Software, DateTime
		if (Array.Exists(ifd0Tags, t => t == tagId))
			return TryGetExifValue(exifPayload, ifd0, littleEndian, tagId, out value);

		int exifIfdOffset;
		var exifIfdTag = 0x8769; // Tag for Exif IFD Pointer
		if (!TryGetExifOffsetTag(exifPayload, ifd0, littleEndian, exifIfdTag, out exifIfdOffset)) return false;
		return TryGetExifValue(exifPayload, tiffStart + exifIfdOffset, littleEndian, tagId, out value);
	}

	/**
	 * Reads the EXIF date from a JPEG file stream.
	 * @param br The BinaryReader for the JPEG file stream.
	 * @returns True if the file is a JPEG, false otherwise.
	 */
	public bool IsJPEG()
	{
		return br.ReadByte() == 0xFF && br.ReadByte() == 0xD8;
	}

	public string ReadExifTag(int tagId)
	{
		if (!IsJPEG()) return null;

		var fs = br.BaseStream;

		while (fs.Position < fs.Length)
		{
			int prefix = br.ReadByte();
			if (prefix < 0) return null;
			while (prefix != 0xFF && fs.Position < fs.Length)
				prefix = br.ReadByte();
			if (prefix < 0) return null;

			int marker = br.ReadByte();
			if (marker < 0) return null;
			while (marker == 0xFF && fs.Position < fs.Length)
				marker = br.ReadByte();
			if (marker < 0) return null;

			if (marker == 0xD9 || marker == 0xDA) break;
			if (marker == 0x01 || (marker >= 0xD0 && marker <= 0xD7)) continue;

			ushort segmentLength = ReadBigEndianUInt16();
			if (segmentLength < 2) return null;
			int payloadLength = segmentLength - 2;

			if (marker == 0xE1)
			{
				var payload = br.ReadBytes(payloadLength);
				if (payload.Length != payloadLength) return null;

				string value;
				if (TryReadExifTag(payload, tagId, out value))
					return value;
			}
			else
			{
				fs.Seek(payloadLength, SeekOrigin.Current);
			}
		}
		return null;
	}

	public static void RunExampleTests()
	{
		if (ReadExampleTag(Example_NotJPEG, 0x0132) != null)
			throw new InvalidOperationException("Example_NotJPEG should not be parsed as JPEG.");

		if (ReadExampleTag(Example_JPEG_NoExif, 0x0132) != null)
			throw new InvalidOperationException("Example_JPEG_NoExif should not contain EXIF date tags.");

		const string expectedDate = "2007:06:14 01:46:58";
		if (ReadExampleTag(Example_JPEG_WithExifDate, 0x0132) != expectedDate)
			throw new InvalidOperationException("Example_JPEG_WithExifDate DateTime tag mismatch.");
		if (ReadExampleTag(Example_JPEG_WithExifDate, 0x9003) != expectedDate)
			throw new InvalidOperationException("Example_JPEG_WithExifDate DateTimeOriginal tag mismatch.");
		if (ReadExampleTag(Example_JPEG_WithExifDate, 0x9004) != expectedDate)
			throw new InvalidOperationException("Example_JPEG_WithExifDate DateTimeDigitized tag mismatch.");
	}

	private static string ReadExampleTag(byte[] data, int tagId)
	{
		using (var ms = new MemoryStream(data))
		using (var br = new BinaryReader(ms))
		using (var reader = new ExifReader(br))
		{
			return reader.ReadExifTag(tagId);
		}
	}

